#!/bin/sh
# Enhanced MakeMKV launcher with log monitoring

export HOME=/config
export QT_QPA_PLATFORM=xcb
export QT_XCB_GL_INTEGRATION=none

# Ensure MakeMKV config directory exists
mkdir -p /config/.MakeMKV

# Ensure critical settings for our enhanced features
SETTINGS_FILE="/config/.MakeMKV/settings.conf"
if [ -f "$SETTINGS_FILE" ]; then
    # Update existing settings
    grep -q "app_ShowDebug" "$SETTINGS_FILE" || echo 'app_ShowDebug = "1"' >> "$SETTINGS_FILE"
    grep -q "app_ExpertMode" "$SETTINGS_FILE" || echo 'app_ExpertMode = "1"' >> "$SETTINGS_FILE"
    grep -q "app_DestinationType" "$SETTINGS_FILE" || echo 'app_DestinationType = "2"' >> "$SETTINGS_FILE"
    
    # Force enable if they exist but are disabled
    sed -i 's/app_ShowDebug = "0"/app_ShowDebug = "1"/' "$SETTINGS_FILE"
    sed -i 's/app_ExpertMode = "0"/app_ExpertMode = "1"/' "$SETTINGS_FILE"
    
    # Check if DestinationType is set correctly for title extraction
    if grep -q 'app_DestinationType = "1"' "$SETTINGS_FILE"; then
        echo "[WARNING] MakeMKV DestinationType is set to 'Flat' - movie titles in notifications will show as 'Unknown Title'"
        echo "[WARNING] Change to 'Semi-automatic' in MakeMKV preferences for best chance at successful title detection"
    fi
else
    # Create minimal settings file with our requirements
    cat > "$SETTINGS_FILE" << EOF
#
# MakeMKV settings file, auto-generated by enhanced container
#
app_ShowDebug = "1"
app_ExpertMode = "1"
app_DestinationType = "2"
app_DestinationDir = "/output"
EOF
fi

DEBUG_ARGS=
if is-bool-val-true "${CONTAINER_DEBUG:-1}"; then
    mkdir -p /config/log/makemkv
    DEBUG_ARGS="debug /config/log/makemkv/debug.txt"
fi

# Start the log watcher in the background
/usr/local/bin/log-watcher.sh &

cd /storage
exec /opt/makemkv/bin/makemkv $DEBUG_ARGS -std

